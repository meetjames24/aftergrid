#!/usr/bin/env python3
"""Rebuild aftergrid-i18n.js: Greek block kept from the existing file, other languages from langs.py."""
import json, subprocess, sys
sys.path.insert(0, ".")
from langs import ASK, EL_ASK, FR, DE, PT, TR
P = "../build/config/includes.chroot/usr/share/aftergrid/portal/aftergrid-i18n.js"
el = json.loads(subprocess.check_output(["node", "-e",
  f"eval(require('fs').readFileSync('{P}','utf8').replace('const AFTERGRID_I18N','global.X'));console.log(JSON.stringify(X.el))"]))
keys = [k for k in el if k not in ASK]
assert len(keys) == 110, len(keys)
el.update(dict(zip(ASK, EL_ASK)))
out = {"el": el}
for code, lst in (("fr", FR), ("de", DE), ("pt", PT), ("tr", TR)):
    assert len(lst) == len(keys) + len(ASK), (code, len(lst))
    out[code] = dict(zip(keys + ASK, lst))
NAMES = {"en": "English", "el": "Ελληνικά", "fr": "Français", "de": "Deutsch", "pt": "Português", "tr": "Türkçe"}
open(P, "w").write("// Aftergrid portal translations: generated by i18n/gen.py (edit langs.py, not this file).\n"
                   "// English is the source text; each language maps English -> translation. Missing keys fall back to English.\n"
                   f"const AFTERGRID_LANGS = {json.dumps(NAMES, ensure_ascii=False)};\n"
                   f"const AFTERGRID_I18N = {json.dumps(out, ensure_ascii=False, indent=1)};\n")
print({k: len(v) for k, v in out.items()})
